package apap.domain.port

import java.time.Duration

/**
 * FR-EXE-006 Scheduler の実行単位（ADR-0032）。
 *
 * APAPは**周期実行のスレッドを自分では持たない**。埋込ライブラリ（`apap-runtime`）が
 * 勝手に常駐スレッドを起こすと、宿主のライフサイクル管理（起動順序・停止・スレッド数の制御）と
 * 衝突するため（CLAUDE.md 不変条件6の趣旨）。代わりに「何を・どの間隔で実行すべきか」だけを
 * このPortで宣言し、駆動は宿主（またはGateway）に委ねる。
 *
 * ## 実装側の要件
 *
 * [runOnce] は**多重起動に対して冪等**でなければならない。複数ノード構成では同じタスクが
 * 同時に走りうるし（NFR-AVL-003）、05_シーケンス設計.md 5.10 が定めるリーダー選出があっても
 * 切り替わり中やネットワーク分断中には二重実行が起こる。リーダー選出を
 * 「二重実行が起きない保証」として扱うのは、機構の存在と機構の有効性を混同することになる。
 *
 * ## 呼び出し側の要件
 *
 * [runOnce] が投げた例外で駆動ループを止めないこと。1つのタスクの失敗が
 * 他のタスクの周期実行を巻き添えにしてはならない。
 */
interface ScheduledTask {
    /** ログ・メトリクス用の識別子。`[a-z-]+` を想定。 */
    val name: String

    /** 実行間隔。駆動側はこの間隔を下回らない頻度で [runOnce] を呼ぶ。 */
    val interval: Duration

    /** 1回分の処理。冪等であること。 */
    suspend fun runOnce()
}
